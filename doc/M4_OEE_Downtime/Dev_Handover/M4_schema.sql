-- ---------------------------------------------------------------------
-- 12. Serving view — roll up by SUMMING quantities, THEN dividing.
--     Demonstrates the no-average rule structurally (§4).
-- ---------------------------------------------------------------------
CREATE VIEW oee.v_oee_rollup AS
SELECT
  tenant_id,
  work_unit_ref,
  date_trunc('day', bucket_start)                                   AS day,
  SUM(planned_production_min)                                       AS ppt_min,
  SUM(operating_time_min)                                           AS operating_min,
  SUM(total_count)                                                  AS total_count,
  SUM(good_count)                                                   AS good_count,
  CASE WHEN SUM(planned_production_min) > 0
       THEN SUM(operating_time_min) / SUM(planned_production_min) END AS availability,
  CASE WHEN SUM(operating_time_min) > 0
       THEN (SUM(total_count) * MAX(ideal_cycle_time_sec) / 60.0) / SUM(operating_time_min) END AS performance,
  CASE WHEN SUM(total_count) > 0
       THEN SUM(good_count) / SUM(total_count) END                  AS quality
FROM oee.oee_interval
GROUP BY tenant_id, work_unit_ref, date_trunc('day', bucket_start);
COMMENT ON VIEW oee.v_oee_rollup IS 'Daily OEE roll-up computed by summing quantities then dividing — never by averaging interval percentages (deep-plan §4).';
