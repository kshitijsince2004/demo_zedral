  scope_node_ref            BIGINT REFERENCES canon.equipment_node(node_id),   -- asset/line/plant scope
  period_start              TIMESTAMPTZ NOT NULL,
  period_end                TIMESTAMPTZ NOT NULL,
  rank_basis                oee.rank_basis NOT NULL,
  rank                      INT NOT NULL CHECK (rank > 0),
  big_loss                  oee.big_loss,
  reason_ref                BIGINT REFERENCES canon.reason_code(reason_id),
  value                     NUMERIC NOT NULL,                     -- minutes / cost / units per rank_basis
  is_other_bucket           BOOLEAN NOT NULL DEFAULT FALSE,       -- governance flag: 'All Other' in top-loss (§6)
  computed_at               TIMESTAMPTZ NOT NULL DEFAULT now(),
  ext                       JSONB NOT NULL DEFAULT '{}'::jsonb
);
CREATE INDEX ix_top_loss_scope ON oee.top_loss (tenant_id, scope_node_ref, period_start DESC, rank_basis, rank);
COMMENT ON TABLE oee.top_loss IS 'Pareto cache of biggest losses by minutes and by cost; flags an over-sized "All Other" bucket for refinement (deep-plan §6).';

